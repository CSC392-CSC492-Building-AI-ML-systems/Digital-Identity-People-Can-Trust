"""
Zero-Knowledge Proof (ZKP) Core Logic Module.

This module provides the foundational cryptographic and mathematical operations 
required for the privacy-preserving age-verification system. It simulates the 
generation and verification of Zero-Knowledge Proofs (ZKPs) using HMAC-based 
commitments to ensure users are 19+ without exposing their actual Date of Birth.
"""

import hashlib
import hmac
from datetime import datetime

# Server secret used for simulating secure cryptographic verification
SERVER_SECRET = b"mock_backend_secret_key_123"
LEGAL_AGE = 19

def calculate_age(dob_string):
    """
    Calculates the user's current age based on a provided Date of Birth string.

    :param dob_string: The user's date of birth in 'YYYY-MM-DD' format.
    :type dob_string: str
    :return: The calculated age in years.
    :rtype: int
    :raises ValueError: If the date format is incorrect.
    """
    dob = datetime.strptime(dob_string, "%Y-%m-%d")
    today = datetime.today()
    # Subtract 1 year if the current date is before the user's birthday this year
    return today.year - dob.year - ((today.month, today.day) < (dob.month, dob.day))

def generate_proof(user_id, dob_string, nonce):
    """
    Client-side proof generation. 
    
    Generates a cryptographic proof that the user is of legal age (19+) 
    without revealing the actual Date of Birth to the server.

    :param user_id: The unique identifier for the user.
    :type user_id: str
    :param dob_string: The user's date of birth in 'YYYY-MM-DD' format.
    :type dob_string: str
    :param nonce: A one-time secure challenge string provided by the server.
    :type nonce: str
    :return: A dictionary containing the status, user_id, nonce, and the generated proof.
             If the user is underage, the proof will be None and status 'rejected'.
    :rtype: dict
    """
    age = calculate_age(dob_string)
    if age < LEGAL_AGE:
        return {"status": "rejected", "reason": "underage", "proof": None}
    
    # Simulate a zero-knowledge proof payload using HMAC
    message = f"{user_id}:age_verified_19_plus:{nonce}".encode('utf-8')
    proof_hash = hmac.new(SERVER_SECRET, message, hashlib.sha256).hexdigest()
    
    return {
        "status": "success",
        "user_id": user_id,
        "nonce": nonce,
        "proof": proof_hash
    }

def verify_proof(user_id, nonce, proof_hash):
    """
    Server-side proof verification.
    
    Verifies that the provided cryptographic proof is mathematically valid 
    and matches the expected challenge nonce for the specified user.

    :param user_id: The unique identifier for the user.
    :type user_id: str
    :param nonce: The one-time secure challenge string previously issued to the user.
    :type nonce: str
    :param proof_hash: The cryptographic proof generated by the client.
    :type proof_hash: str
    :return: True if the proof is valid, False otherwise.
    :rtype: bool
    """
    expected_message = f"{user_id}:age_verified_19_plus:{nonce}".encode('utf-8')
    expected_hash = hmac.new(SERVER_SECRET, expected_message, hashlib.sha256).hexdigest()
    
    # hmac.compare_digest prevents timing attacks
    return hmac.compare_digest(expected_hash, proof_hash)